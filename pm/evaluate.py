"""Offline evaluation on a simulated fleet. Writes docs/evaluation.md.

    python -m pm.evaluate
"""
import pathlib

from . import models, sim


def main():
    _, m = models.train()
    r, a = m["rul"], m["anomaly"]
    lines = ["# Evaluation", "",
             f"Generated by `python -m pm.evaluate`: {sum(m['assets'].values())} simulated machines run to failure ({m['assets']['train']} to train, {m['assets']['calibrate']} to calibrate,",
             f"{m['assets']['test']} held out), {m['windows']['train'] + m['windows']['test']:,}+ vibration windows, four failure modes. The data is simulated, so this shows the methods recover",
             "planted wear patterns; it does not show performance on real machines.", "",
             "## 1. Remaining useful life", "",
             "Scored on the held-out machines, in their last 300 hours (where a wrong answer costs money).", "",
             "| | Mean absolute error |", "|---|---|",
             f"| Quantile gradient boosting, median (`{models.VERSION}`) | {r['mae_h_last_300h']} h |",
             f"| Baseline: average life of the fleet minus the machine's age | {r['baseline_mean_life_minus_age_mae_h']} h |", "",
             f"The 10-90% band should hold the true value 80% of the time. Straight from the models it held {r['coverage_raw_10_90']:.1%}; after conformal calibration on machines",
             f"the models never saw (widening by {r['conformal_adjustment_h']} h each side) it held {r['coverage_conformal']:.1%}. Mean band width in the last 300 hours: {r['mean_band_width_h_last_300h']} h.", "",
             "## 2. Anomaly detection", "",
             "Three alarms, each set to the same false-alarm rate (0.5% of healthy windows on the calibration machines) and required to fire on two windows in a row.",
             "Warning time = hours of life left when the alarm first fires; a machine that never alarms counts as zero.", "",
             "| Alarm | Median warning | Machines never alarmed | Machines alarmed while still healthy |", "|---|---|---|---|",
             f"| Distance from the machine's own healthy baseline, five indicators together | {a['median_warning_h']['distance']} h | {a['assets_never_alarmed']['distance']} of {m['assets']['test']} | {a['assets_alarmed_while_healthy']['distance']} |",
             f"| Overall vibration level (RMS) against its healthy baseline | {a['median_warning_h']['rms']} h | {a['assets_never_alarmed']['rms']} of {m['assets']['test']} | {a['assets_alarmed_while_healthy']['rms']} |",
             f"| Isolation forest on the same five indicators | {a['median_warning_h']['isolation_forest']} h | {a['assets_never_alarmed']['isolation_forest']} of {m['assets']['test']} | {a['assets_alarmed_while_healthy']['isolation_forest']} |", "",
             "| Failure mode | Distance | RMS level | Isolation forest |", "|---|---|---|---|"]
    lines += [f"| {k.replace('_', ' ')} | {v['distance']} h | {v['rms']} h | {v['isolation_forest']} h |" for k, v in a["median_warning_h_by_mode"].items()]
    lines += ["", "The isolation forest was the blueprint's suggested baseline and the first thing built. It failed in an instructive way: its score saturates. A point far outside",
              "the healthy cloud is isolated in about as few splits as a point just outside it, so a badly worn machine scored no higher than the odd healthy outlier, and",
              f"{a['assets_never_alarmed']['isolation_forest']} of {m['assets']['test']} machines never crossed a threshold set for a 0.5% false-alarm rate. A plain distance from the healthy baseline keeps growing as wear grows.", "",
              "## 3. Failure-mode classifier", "",
              f"On windows from the last 40% of life of held-out machines: {m['mode']['accuracy_last_40pct_of_life']:.1%} correct across four modes (guessing: 25%).",
              "The four simulated modes leave cleanly different fingerprints (1x shaft speed, 2x shaft speed, the bearing defect line, high-frequency noise), which is why this is near-perfect here",
              "and would not be on real machines, where faults overlap.", "",
              "## Simulator", "",
              f"Windows are {sim.N} samples at {sim.FS} Hz every {sim.STEP_H:.0f} hours. Wear grows with the cube of the share of life used. Shaft-rate tones vary with a random load",
              "factor (15%) from window to window, which is what makes a plain level alarm noisy."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
